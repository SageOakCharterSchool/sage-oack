    protected function getModelNames($type = null): array
    {
        $path = app_path('Models') . '/*.php';
        $models = collect(glob($path))->map(fn($file) => basename($file, '.php'))->toArray();
        if ($type == "fileInfo") {
            $modelsToExclude = [
                'User',
                'LogActivity',
                'FileUploads',
                'Cycle',
                'ActivityLogs',
                'GlobalActions',
                'UsersEnabledToImpersonate',
            ];
        } else {
            $modelsToExclude = [
                'User',
                'LogActivity',
                'FileUploads',
                'Cycle',
                'ActivityLogs',
                'TeacherStudent',
                'GlobalActions',
                'UsersEnabledToImpersonate',
            ];
        }

        $models = Arr::where($models, function ($value, $key) use ($modelsToExclude) {
            if (!in_array($value, $modelsToExclude)) {
                return $value;
            }
        });

        return $models;
    }

